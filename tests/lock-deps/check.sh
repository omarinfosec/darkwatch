#!/usr/bin/env bash
# Checks on ops/lock-deps.sh, with uv stubbed (no network):
#   - --check passes on the repo's own requirements.in/.lock pairs;
#   - --check fails on a lock that is behind its .in (a bumped or added
#     pin), a missing lock or requirements.in and an .in line that is not name==version, and
#     matches names as pip does (case, -_. and extras);
#   - a lock run calls the pinned uv with the flags the locks are made with
#     (CPython 3.13, x86_64 Linux, hashes) for each image, resolves each
#     again for aarch64 Linux from a copy of the new lock, fails when that
#     gives a different lock, and never uses a uv of another version.
#   bash tests/lock-deps/check.sh
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
uv_version="$(sed -n 's/^UV_VERSION=//p' "$repo/ops/lock-deps.sh")"
[[ -n "$uv_version" ]] || { echo "FAIL: no UV_VERSION= in ops/lock-deps.sh" >&2; exit 1; }
passed=0

ok()   { echo "ok   $*"; passed=$((passed + 1)); }
fail() { echo "FAIL $*" >&2; exit 1; }

# ─── The repo's own locks ──────────────────────────────────────────────────
bash "$repo/ops/lock-deps.sh" --check >/dev/null || fail "repo locks are stale"
ok "the repo's requirements.lock files cover their requirements.in"

# ─── A throwaway tree: ops/lock-deps.sh with fake requirement files ────────
tree="$work/tree"
mkdir -p "$tree/ops" "$tree/darkwatch" "$tree/setup"
cp "$repo/ops/lock-deps.sh" "$tree/ops/"

write_good() {
    cat > "$tree/darkwatch/requirements.in" <<'EOF'
# comment
PySocks==1.7.1
python_socks[asyncio]==3.2.1   # trailing comment

Zope.Interface==7.0
EOF
    cat > "$tree/darkwatch/requirements.lock" <<'EOF'
# This file was autogenerated by uv via the following command:
#    ./ops/lock-deps.sh
async-helper==1.0 \
    --hash=sha256:00
    # via python-socks
pysocks==1.7.1 \
    --hash=sha256:11
    # via -r darkwatch/requirements.in
python-socks==3.2.1 \
    --hash=sha256:22
zope-interface==7.0 \
    --hash=sha256:33
EOF
    printf 'fastapi==0.1.0\n' > "$tree/setup/requirements.in"
    printf 'fastapi==0.1.0 \\\n    --hash=sha256:44\n' > "$tree/setup/requirements.lock"
}

check_fails() {   # description, expected message
    local out
    if out="$(bash "$tree/ops/lock-deps.sh" --check 2>&1)"; then
        fail "$1: --check passed"
    fi
    grep -qF -- "$2" <<<"$out" || fail "$1: no '$2' in: $out"
    ok "$1 fails --check"
}

write_good
bash "$tree/ops/lock-deps.sh" --check >/dev/null || fail "matching tree failed --check"
ok "names match across case, -_. and extras; comments and blank lines are skipped"

write_good
sed -i 's/^PySocks==1.7.1/PySocks==1.7.2/' "$tree/darkwatch/requirements.in"
check_fails "a bumped pin" "pysocks==1.7.2"

write_good
echo "newpkg==1.0" >> "$tree/setup/requirements.in"
check_fails "an added pin" "setup/requirements.lock is behind"

write_good
printf 'pysocks==1.7.1 \\\n    --hash=sha256:11\n    # via zope-interface==7.0\n' \
    > "$tree/darkwatch/requirements.lock"
check_fails "a pin named only in a comment of the lock" "zope-interface==7.0"

write_good
rm "$tree/setup/requirements.lock"
check_fails "a missing lock" "setup/requirements.lock is missing"

write_good
rm "$tree/setup/requirements.in"
check_fails "a missing requirements.in" "setup/requirements.in is missing"

write_good
echo "requests>=2.0" >> "$tree/darkwatch/requirements.in"
check_fails "an unpinned requirement" "not pinned as name==version: requests>=2.0"

# ─── Lock runs, uv stubbed ─────────────────────────────────────────────────
# The stub writes a lock holding the .in's pins, so the final --check passes.
stubs="$work/bin"
mkdir -p "$stubs"
cat > "$stubs/uv" <<EOF
#!/usr/bin/env bash
if [[ "\$1" == --version ]]; then echo "uv \${STUB_UV_VERSION:-$uv_version}"; exit 0; fi
printf '%s\n' "\$*" >> "$work/uv.log"
args="\$*"; out=""; in=""
while [[ \$# -gt 0 ]]; do
    case "\$1" in
        -o) out="\$2"; shift ;;
        *.in) in="\$1" ;;
    esac
    shift
done
grep -E '^[A-Za-z]' "\$in" | sed 's/\[[^]]*\]//; s/[[:space:]].*//; s/\$/ \\\\/' > "\$out"
# A package that only the aarch64 resolution pulls in.
[[ -z "\${STUB_ARCH_DIFF:-}" || "\$args" != *"--python-platform aarch64-unknown-linux-gnu"* ]] \
    || echo "arm-only==1.0 \\\\" >> "\$out"
EOF
cat > "$stubs/python3" <<EOF
#!/usr/bin/env bash
echo "python3 \$*" >> "$work/uv.log"
exit 1
EOF
chmod +x "$stubs/uv" "$stubs/python3"

write_good
: > "$work/uv.log"
(cd "$work" && PATH="$stubs:$PATH" bash "$tree/ops/lock-deps.sh" >/dev/null) \
    || fail "lock run with the pinned uv failed"
# The aarch64 run writes to a temporary copy of the lock; its path varies.
sed -i -E 's| -o /[^ ]*/other\.lock$| -o TMP/other.lock|' "$work/uv.log"
flags="--python-version 3.13 --python-platform"
rest="--generate-hashes --custom-compile-command ./ops/lock-deps.sh"
want="pip compile --quiet $flags x86_64-unknown-linux-gnu $rest darkwatch/requirements.in -o darkwatch/requirements.lock
pip compile --quiet $flags aarch64-unknown-linux-gnu $rest darkwatch/requirements.in -o TMP/other.lock
pip compile --quiet $flags x86_64-unknown-linux-gnu $rest setup/requirements.in -o setup/requirements.lock
pip compile --quiet $flags aarch64-unknown-linux-gnu $rest setup/requirements.in -o TMP/other.lock"
[[ "$(cat "$work/uv.log")" == "$want" ]] || fail "uv calls: $(cat "$work/uv.log")"
grep -q '^pysocks==1.7.1\|^PySocks==1.7.1' "$tree/darkwatch/requirements.lock" \
    || fail "the lock was not written in the repo root"
ok "a lock run calls uv $uv_version for each image: Python 3.13, x86_64 then aarch64 Linux, hashes"

write_good
: > "$work/uv.log"
PATH="$stubs:$PATH" bash "$tree/ops/lock-deps.sh" --upgrade >/dev/null || fail "--upgrade run failed"
[[ "$(grep -c '^pip compile --quiet --upgrade --python-version 3.13 --python-platform x86_64-' "$work/uv.log")" == 2 ]] \
    || fail "--upgrade not passed to uv: $(cat "$work/uv.log")"
grep -q -- '--upgrade.*aarch64' "$work/uv.log" && fail "--upgrade passed to the aarch64 run: $(cat "$work/uv.log")"
ok "--upgrade is passed on to uv for the lock, not for the aarch64 comparison"

write_good
if out="$(STUB_ARCH_DIFF=1 PATH="$stubs:$PATH" bash "$tree/ops/lock-deps.sh" 2>&1)"; then
    fail "a lock run passed although aarch64 resolves to another lock"
fi
grep -qF "darkwatch/requirements.in resolves differently on aarch64-unknown-linux-gnu" <<<"$out" \
    || fail "no platform difference reported: $out"
grep -qF "arm-only==1.0" <<<"$out" || fail "the difference is not shown: $out"
ok "a lock run fails when aarch64 resolves to another lock, and shows the difference"

write_good
: > "$work/uv.log"
if STUB_UV_VERSION=0.0.1 PATH="$stubs:$PATH" bash "$tree/ops/lock-deps.sh" >/dev/null 2>&1; then
    fail "a lock run with only a uv of another version passed"
fi
grep -q '^pip compile' "$work/uv.log" && fail "a uv of another version was used"
grep -q '^python3 -m venv' "$work/uv.log" || fail "the pinned uv was not fetched: $(cat "$work/uv.log")"
ok "a uv of another version is not used; the pinned one is fetched instead"

echo "$passed checks passed"
